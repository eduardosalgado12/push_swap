#include "push_swap.h"

void	swap(t_stack **stack)
{
	t_stack	*first;
	t_stack	*second;

	if (!stack || !*stack || !(*stack)->next)
		return ;
	first = *stack;
	second = first->next;
	first->next = second->next;
	second->next = first;
	*stack = second;
}

void	sa(t_stack **a)
{
	swap(a);
	write_op("sa");
}

void	sb(t_stack **b)
{
	swap(b);
	write_op("sb");
}

void	ss(t_stack **a, t_stack **b)
{
	swap(a);
	swap(b);
	write_op("ss");
}
